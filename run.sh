#!/usr/bin/env bash
# STATUS:
#   BUILT: starts the local RangeServer, waits for HTTP readiness, runs the
#          benchmark harness against it, and always cleans up via a trap.
#          Kills stale RangeServer/harness processes on the chosen port first.
#          Verified end-to-end against src/core on the synthetic 8-layer model.
#   TBD:   production MinIO/S3 + tc validation and a real checkpoint; current
#          numbers are synthetic (results/benchmark.csv).
#   PACKAGES: aiohttp, psutil, requests (run `bash setup.sh` once).
#
# The default benchmark model is the 8-layer synthetic file (steady-state
# overlap is visible); models/synthetic_2layer.safetensors is the minimal
# integration artifact generated by setup.sh.
#
# Usage:
#   bash run.sh
#   PORT=8765 BANDWIDTH=8 RUNS=3 LOOKAHEAD=2 WORK_FACTOR=1.0 MODE=both bash run.sh
#
# Environment overrides:
#   PORT (8765), HOST (127.0.0.1), FILE (models/synthetic_8layer.safetensors),
#   LAYERS (8), BANDWIDTH (8 Mbit/s), RUNS (3), LOOKAHEAD (2), WORK_FACTOR (1.0),
#   MODE (both|baseline|pipeline), OUT (results/benchmark.csv), MODEL_MB (8).

set -euo pipefail

ROOT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
cd "$ROOT_DIR"

PYTHON="${PYTHON:-python3}"
HOST="${HOST:-127.0.0.1}"
PORT="${PORT:-8765}"
FILE="${FILE:-models/synthetic_8layer.safetensors}"
LAYERS="${LAYERS:-8}"
BANDWIDTH="${BANDWIDTH:-8}"
RUNS="${RUNS:-3}"
LOOKAHEAD="${LOOKAHEAD:-2}"
WORK_FACTOR="${WORK_FACTOR:-1.0}"
MODE="${MODE:-both}"
OUT="${OUT:-results/benchmark.csv}"
MODEL_MB="${MODEL_MB:-8}"

mkdir -p results models
PIDFILE="results/rangeserver_${PORT}.pid"
SERVER_LOG="results/rangeserver.log"
SERVER_PID=""

cleanup() {
    local status=$?
    if [[ -n "${SERVER_PID}" ]] && kill -0 "${SERVER_PID}" 2>/dev/null; then
        echo "Stopping RangeServer (pid ${SERVER_PID})..."
        kill "${SERVER_PID}" 2>/dev/null || true
        for _ in $(seq 1 20); do
            kill -0 "${SERVER_PID}" 2>/dev/null || break
            sleep 0.1
        done
        if kill -0 "${SERVER_PID}" 2>/dev/null; then
            kill -9 "${SERVER_PID}" 2>/dev/null || true
        fi
        wait "${SERVER_PID}" 2>/dev/null || true
    fi
    rm -f "${PIDFILE}"
    exit "${status}"
}
trap cleanup EXIT INT TERM

# --- clean stale servers on this port -------------------------------------
if [[ -f "${PIDFILE}" ]]; then
    OLD_PID="$(cat "${PIDFILE}" 2>/dev/null || true)"
    if [[ -n "${OLD_PID}" ]] && kill -0 "${OLD_PID}" 2>/dev/null; then
        echo "Killing stale RangeServer pid ${OLD_PID} from ${PIDFILE}"
        kill "${OLD_PID}" 2>/dev/null || true
        sleep 0.3
    fi
    rm -f "${PIDFILE}"
fi
# Pattern is specific to our module + port; never kill unrelated processes.
pkill -f "src\.storage\.RangeServer.*--port ${PORT}([^0-9]|$)" 2>/dev/null || true
# A previous foreground harness could still be running against this port.
pkill -f "src\.bench\.BenchmarkHarness.*--url http://${HOST}:${PORT}/" 2>/dev/null || true
sleep 0.2

# --- preflight -------------------------------------------------------------
if ! "${PYTHON}" -c "import psutil" >/dev/null 2>&1; then
    echo "WARNING: psutil is missing; RSS measurements will use /proc fallback." >&2
    echo "         Run 'bash setup.sh' to install declared dependencies." >&2
fi
if ! "${PYTHON}" -c "import aiohttp" >/dev/null 2>&1; then
    echo "NOTE: aiohttp is not installed. The fallback engine only needs the stdlib;" >&2
    echo "      src/core may require aiohttp. Run 'bash setup.sh' before integration." >&2
fi

if [[ ! -s "${FILE}" ]]; then
    echo "Model file missing; generating ${FILE} (${MODEL_MB} MiB, ${LAYERS} layers)..."
    "${PYTHON}" -m src.bench.make_synthetic_model \
        --out "${FILE}" --layers "${LAYERS}" --size-mb "${MODEL_MB}"
fi

# --- start server ----------------------------------------------------------
echo "Starting RangeServer on ${HOST}:${PORT} (${BANDWIDTH} Mbit/s shared)..."
"${PYTHON}" -m src.storage.RangeServer \
    --file "${FILE}" \
    --host "${HOST}" \
    --port "${PORT}" \
    --bandwidth-mbps "${BANDWIDTH}" \
    --log >"${SERVER_LOG}" 2>&1 &
SERVER_PID=$!
echo "${SERVER_PID}" >"${PIDFILE}"

URL="http://${HOST}:${PORT}/model.safetensors"
READY=0
for _ in $(seq 1 60); do
    if ! kill -0 "${SERVER_PID}" 2>/dev/null; then
        echo "ERROR: RangeServer exited during startup. Log:" >&2
        tail -n 40 "${SERVER_LOG}" >&2 || true
        exit 1
    fi
    CODE="$(curl -s -o /dev/null -w '%{http_code}' -H 'Range: bytes=0-0' "${URL}" 2>/dev/null || true)"
    if [[ "${CODE}" == "206" ]]; then
        READY=1
        break
    fi
    sleep 0.2
done
if [[ "${READY}" -ne 1 ]]; then
    echo "ERROR: RangeServer did not become ready at ${URL} (last HTTP code: ${CODE:-none})." >&2
    tail -n 40 "${SERVER_LOG}" >&2 || true
    exit 1
fi
echo "RangeServer ready: ${URL}"

# --- run harness (propagate its exit status honestly) ----------------------
set +e
"${PYTHON}" -m src.bench.BenchmarkHarness \
    --file "${FILE}" \
    --url "${URL}" \
    --bandwidth-mbps "${BANDWIDTH}" \
    --runs "${RUNS}" \
    --lookahead "${LOOKAHEAD}" \
    --work-factor "${WORK_FACTOR}" \
    --mode "${MODE}" \
    --out "${OUT}"
HARNESS_STATUS=$?
set -e

if [[ "${HARNESS_STATUS}" -ne 0 ]]; then
    echo "Harness exited with status ${HARNESS_STATUS}." >&2
    echo "Last RangeServer log lines:" >&2
    tail -n 20 "${SERVER_LOG}" >&2 || true
fi

exit "${HARNESS_STATUS}"
